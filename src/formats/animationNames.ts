/** The sequence's name split into words ("EmoteSitGround" -> "Emote Sit Ground"), or "Animation N" when unlisted. */
export function animationName(id: number): string {
	const name = ANIMATION_NAMES.get(id);
	if (!name) return `Animation ${id}`;
	// Words start at a capital after a lowercase letter, at the last capital of a run ("NPCWelcome"), and at a digit ("Attack1H").
	return name.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2').replace(/([a-zA-Z])(\d)/g, '$1 $2');
}
